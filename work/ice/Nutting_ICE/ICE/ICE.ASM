; ******************
; * INITIALIZATION *
; ******************
	.LOC	ICEROM
	JMP	ICE	;GET PC TO F003
ICE:	LXI	SP,STACK
	XRA	A	; ZERO ALL THE MAPS
	MVI	B,5
	LXI	H,DMPLOW
..CLR:	MOV	M,A
	INX	H
	DJNZ	..CLR
	LXI	B,EXTL+800H	; AND TURN ON STUFF
..INIT:	OUTP	A
	INR	C
	JRNZ	..INIT
	; TURN ON THE MESSAGES
	INR	A
	OUT	CENABLE
	; INITIALIZE THE USARTS
	LXI	B,CRTS+0200H
	LXI	D,0AE40H	; INITIALIZATION DATA
	LXI	H,4E27H		; *16\8 BITS\NO PARITY\1STOP
..ILP1:	;INP	A
;	RRC
;	JRNC	..ILP1
..ILP2:	OUTP	D
	OUTP	E
	OUTP	H
	OUTP	L
	DCR	C	; ==CRTD
	INP	A	; FLUSH THE DATA
	INP	A
	MVI	C,LPTS
	DJNZ	..ILP1
	; INIT THE RAM
	LXI	H,STACK
	SHLD	MONSP	; SET UP REASONABLE MONITOR STACK
	MVI	A,1	; ICE SIGNON
	CALL    PRINTM
	JMP	MAINLOOP
	.PAGE
; *****************************************
; **
; **  CRTOUT - SEND A CHARACTER TO THE CRT
; **
; ** ENTRY -  A -> CHARACTER
; **
; ** EXIT  -  EVERYTHING RESTORED
; **
; *****************************************
PUNCH:
CONOUT:	MOV	A,C
CRTOUT:	PUSH    B
	MVI	C,CRTS
	JMPR	UART


; **************************************************
; **
; **  LPTOUT - SEND CHARACTER TO PRINTER, EAT CR'S
; **	WAIT FOR DATASET READY.
; **
; **  ENTRY -  A -> CHARACTER
; **
; **  EXIT  -  ALL RESTORED
; **
; **************************************************
LPTOUT:	CPI	0DH	; NO CARRIAGE RETURN
	RZ
	PUSH	B
	MVI	C,LPTS
..LPT:	INP	B
	BIT	7,B	; DATA SET READY
	JRZ	..LPT
UART:	INP	B
	BIT	0,B
	JRZ	UART
	DCR	C
	OUTP	A
	POP	B
	RET
	.PAGE
; *******************************************
; **
; **  NON MASKABLE INTERUPT  -  BREAKPOINT PROCESSING
; **
; *******************************************
	.LOC	ICEROM+66H	; NMI POINT
	JMP	NMI	; CHANGE TOP ADDRESS BITS TO REAL ADDR
NMI:	STA	AFSAVE
	IN	FIFO
	STA	PCSAVE+1
	IN	FIFO
	STA	PCSAVE
	IN	FIFO	; SHOULD BE A AGAIN
	INX	SP
	INX	SP
	LSPD	SPSAVE
	LXI	SP,AFSAVE+2	;PUSH EVERYTHING
	PUSH	PSW
	XRA	A
	OUT	BTYPE
	INR	A	; WRITE PROTECT
	OUT	MISC
	PUSH	B
	PUSH	D
	PUSH    H
	PUSH	X
	PUSH	Y
	EXAF
	PUSH	PSW
	EXX
	PUSH	B
	PUSH	D
	PUSH	H
;	LSPD	MONSP
	LXI	SP,STACK
	LDAI		; CHECK INTERUPTS
	MVI	A,0FFH	; ENABLED
	JPE	..NMI2
	XRA	A
..NMI2:	STA	IFF
	LXI	H,NMIJP
	PCHL
	.PAGE
LIST:	LDA	IOBYTE
	ANI	0C0H
	CPI	80H
	MOV	A,C
	JNZ	PUNCH
	JMP	LPTOUT
; ******************************************
; **
; **  PRINTM  -  PRINT MESSAGE FROM A POOL OF MESSAGES
; **
; **  ENTRY -  A -> NUMBER OF THE MESSAGE
; **
; **  EXIT  -  A -> ZORKED
; **		H -> ZORKED
; **
; ******************************************
PRINTM:	LXI	H,MESSAGES
	ORA	A
	JRZ	CONOMSG
	PUSH	B
	MOV	B,A
..LOOP:	MOV	A,M
	ANI	80H
	INX	H
	JRZ	..LOOP
	DJNZ	..LOOP
	POP	B
; ***********************************
; **
; **  CONOMSG  -  PRINT MESSAGE ON CONSOLE
; **
; **  ENTRY  -  HL -> STRING ENDD BY BYTE WITH SIGN BIT ON
; **
; **  EXIT  -   A -> ZORKED
; **H -> ZORKED
; **
; ***********************************
CONOMSG:MOV	A,M
	CALL	CRTOUT
	BIT	7,A	; TERMINATED BY BIT 7 ON
	RNZ
	INX	H
	JMPR	CONOMSG
	.PAGE
; *********************************
; **
; **  GETCHR - GET A CHARACTER FROM THE CRT AND
; **	FORCE TO UPPER CASE
; **
; **  EXIT -  A -> CHARACTER
; **
; *********************************
GETCHR:	CALL	CRTIN
	CPI	060H	;IS CHAR LOWER CASE???
	RM		;RETURN IF CHAR OK
	ANI	05FH	;FORCE IT TO UPPER CASE
	RET

CONIN:
READER:
CRTIN:	CALL	CRTSTAT
	JRZ	CRTIN
	IN	CRTD
	ANI	7FH
	CPI	5FH
	RNZ
	MVI	A,7FH
	RET


LPTIN:	CALL	LPTSTAT
	JRZ	LPTIN
	IN	LPTD
	RET


CONSTAT:
CRTSTAT:	PUSH	B
	MVI	C,CRTS
	JMPR	UARTSTAT


LPTSTAT:	PUSH	B
	MVI	C,LPTS
UARTSTAT:	INP	A
	POP	B
	ANI	2	; DATA READY?
	RZ	
	MVI	A,0FFH	; TRUE FOR CP\M
	RET

; ***************************
; **  INPUT ROUTINE FOR DEBUG
; ***************************
INCHAR:	CALL	GETCHR
	CPI	CTRLX
	RNZ	
	JMP	DEBUG
	.PAGE
; ***********************
; **
; **  UPPER LEVEL ICE
; **
; ***********************
ERROR:	MVI	A,0	; PRINT 'WHAT?'
	CALL	PRINTM
MAINLOOP:	; PROMPT USER
	MVI	A,2	; %
	CALL	PRINTM
	CALL	GETCHR
	CPI	CTRLC
	JRZ	BOOT	; ^C = BOOT CP\M
	CPI	CTRLX
	JRZ	MAINLOOP   ; ^X = KILL LINE
	CPI	'A'
	JRZ	ARCADESET  ; A = SET ARCADE MODE
	CPI	'C'
	JRZ	COMERCIAL   ; C = SET COMMERCIAL MODE
	CPI	'D'
	JZ	DEBUGE	; D = DEBUG MODE
	JMPR	ERROR



ARCADESET:		; SET MEMORY MAP\WRITE PROTECT
	MVI	A,24
	LXI	D,13H
	LXI	H,0FFFFH
	JMPR	PREBUG


COMERCIAL:
	MVI	A,25
	LXI	D,050F0H
	LXI	H,0FFFFH
;	JMPR	PREBUG


PREBUG:	; SET WRITE PROTECT AND EXTERNAL MAP
	MVI	C,EXTL
	OUTP	E
	INR	C
	OUTP	D
	INR	C
	OUTP	L
	INR	C
	OUTP	H
	CALL	PRINTM
	JMP	DEBUGE
	.PAGE
; ************************************
; **
; **  BOOT - PERFORMS CP\M BOOTSTRAP
; **	READS TRACK 0-SECTOR 1 THRU TRACK 1-SECTOR 20
; **	INTO MEMORY STARTING AT LOAD POINT DETERMINED
; **	BY LOCATION 2 OF TRACK 0-SECTOR 2 MINUS 3 TIMES 256
; **
; ************************************
WBOOT:	.BYTE	3EH
BOOT:	.BYTE	0AFH
	EXAF
	LXI	SP,STACK
	IM0		; 8080 MODE
	MVI	A,4
	OUT	SELECT
	MVI	A,5
	OUT	0EH
	CALL	HOME
	MVI	C,2
	CALL	SETSEC
	LXI	B,BUFFER
	CALL	SETDMA
	CALL	READ
	ORA	A
	JNZ	MAINLOOP
	LDA	BUFFER+2
	SBI	3
	LXI	H,2900H
	MVI	L,0
	MOV	H,A
	PUSH	H
	POP	X
; SUPER BOOT
	MVI	E,25	; NUMBER OF SCTORS
..LP2:	LXI	B,128*256+DATA
	MVI	A,#10011100B	; MULTIPLE READS
	OUT	COMMAND
..LP3:	EI
	HLT
	INI
	JNZ	..LP3
	DCR	E	; NUMBER OF SECTORS TO GO
	MVI	B,128
	JNZ	..LP3
; FORCE INTERUPT
	MVI	A,#11010000B	; IMMEDIATE
	OUT	COMMAND
..LP4:	CALL	DSTAT
	JRNZ	..LP4
	IN	TRACK
	CPI	#1
	JRZ	..LP5
	MVI	A,1
	STA	TRK
	CMA
	OUT	SECTOR
	PUSH	H
	CALL	SEEK
	POP	H
	ORA	A
	JNZ	MAINLOOP
	MVI	E,18	; MORE SECTORS
	JMPR	..LP2
..LP5:	PUSH	X
	POP	H
	LXI	B,1500H
..LP6:	MOV	A,M
	CMA
	MOV	M,A
	INX	H
	DCR	C
	JNZ	..LP6
	DJNZ	..LP6
; DONE READING IN CPM NOW FIX JUMPS IN MEMORY
; AND DO MISC STUFF
	PUSH	X
	POP	D
	LXI	H,WBOOT
	SHLD	1	; JMP ADDR
	MVI	A,0C3H
	STA	0
	STA	5
	LXI	H,806H
	DAD	D
	SHLD	6
	LXI	H,1500H
	DAD	D
	LXI	D,CPMJPS
	XCHG
	LXI	B,15*3
	LDIR
; COLD OR WARM
	EXAF
	ORA	A
	JRNZ	BDONE
; COLD
	LXI	H,0
	SHLD	3	; ZAP IOBYTE AND DISC
	MVI	A,3
	CALL	PRINTM
BDONE:	LDA	4
	ANI	1
	MOV	C,A
	PCIX
	.PAGE
; ********************
; **
; **  CP\M DISC ROUTINES
; **
; ********************
	; HOME DRIVE  -  NO INPUTS
HOME:	XRA	A
	STA	TRK
	MVI	D,3
	LXI	H,.
	MVI	A,#00001110B
	OUT	COMMAND
	JMP	SEEKWAIT


	; SETTRK - SET TRACK TO VALUE IN C REG
SETTRK:	MOV	A,C
	STA	TRK
	RET


	; SETSEC - SET SECTOR TO VALUE IN C REG
SETSEC:	MOV	A,C
	CMA
	OUT	SECTOR
	RET


	; SET DISC NUMBER TO VALUE IN C REGISTER (0-3)
SELDSK:	MOV	A,C
	SET	2,A
	OUT	SELECT
	RET

	; SET BUFFER ADDRESS TO VALUE IN BC REG PAIR
SETDMA:	SBCD	DMA
	RET

	; READ A SECTOR RETURN 0=NO ERRORS 1=ERROR
READ:	CALL	SEEK
	ORA	A
	RNZ	
	MVI	D,4
..READ1:	LHLD	DMA
	LXI	B,128*256+DATA
	MVI	A,#10001100B	; READ COMMAND
	OUT	COMMAND
..LOOP:	EI
	HLT
	INI
	JNZ	..LOOP
; FIX COMPLEMENTED DATA
	LHLD	DMA
	MVI	B,128
..FLP:	MOV	A,M
	CMA
	MOV	M,A
	INX	H
	DJNZ	..FLP
	IN	STATUS	; CHECK UP
	CMA
	ANI	9CH
	RZ	
	DCR	D
	JRNZ	..READ1
	JMP	WRER

	; WRITE A SECTOR. RETURN 0=NO ERRORS, 1=ERROR
WRITE:	CALL	SEEK
	ORA	A
	RNZ	
	LHLD	DMA
	LXI	D,BUFFER
	MVI	B,128
..WLP0:	MOV	A,M
	INX	H
	CMA
	STAX	D
	INX	D
	DJNZ	..WLP0
	MVI	D,3
..ELP:	LXI	H,BUFFER
	LXI	B,8000H+DATA
	MVI	A,#10101100B
	OUT	COMMAND
..OLP:	EI
	HLT
	OUTI
	JNZ	..OLP
	IN	STATUS	; CHECK OPERATION
	CMA
	ANI	0FCH
	RZ	
	DCR	D
	JRNZ	..ELP
WRER:	BIT	7,A
	JNZ	NOTRDY
	MVI	B,15	; WRITE PROTECTED
	BIT	6,A
	JRNZ	WERROR
	MVI	B,16	; WRITE FAULT
	BIT	5,A
	JRNZ	WERROR
	MVI	B,13	; RECORD NOT FOUND
	BIT	4,A
	JRNZ	WERROR
	MVI	B,12	; CRC ERROR
	BIT	3,A
	JRNZ	WERROR
	MVI	B,14	;LOST DATA
WERROR:	MOV	A,B
	CALL	PRINTM
	MVI	A,1
	RET


SEEK:	MVI	D,3	; NUMBER OF RETRYS
	LXI	H,..SK2
	IN	TRACK
	MVI	B,A
	LDA	TRK
	CMA
	CMP	B
	JRNZ	..SK2
	XRA	A
	RET
..SK2:	LDA	TRK
	CMA
	OUT	DATA
	MVI	A,#00011110B	; SEEK,HEAD LOAD, 10MS
	OUT	COMMAND

SEEKWAIT:	CALL DSTAT
	JRNZ	SEEKWAIT
	ANI	00011000B	; SEEK ERROR\CRC ERROR
	RZ	
	DCR	D
	JRZ	SEEKERROR
	PCHL		;RETRY

SEEKERROR:
	BIT	4,A
	MVI	B,11	; SEEK ERROR
	JRNZ	WERROR
	MVI	B,12	; CRC ERROR
	JMPR	WERROR


DSTAT:	IN	STATUS
	CMA
	BIT	7,A
	JRNZ	NOTRDY
	BIT	0,A
	RET


NOTRDY:	MVI	A,10	; NOT READY
	CALL	PRINTM
CPMJPS:	JMP	MAINLOOP

	JMP	WBOOT
	JMP	CONSTAT
	JMP	CONIN
	JMP	CONOUT
	JMP	LIST
	JMP	PUNCH
	JMP	READER
	JMP	HOME
	JMP	SELDSK
	JMP	SETTRK
	JMP	SETSEC
	JMP	SETDMA
	JMP	READ
	JMP	WRITE
	.PAGE
; ***********
; ** DEBUG **
; ***********
DEBUGE:	MVI	A,27
	CALL	PRINTM
	JMPR	DEBUG
DERROR:	MVI	A,0
	CALL	PRINTM
DEBUG:	LXI	SP,STACK
	LXI	H,DEBUG
	SHLD	NMIJP
	MVI	A,9
	CALL	PRINTM
..DB1:	CALL	INCHAR
	CPI	'B'
	JZ	BREAK
	CPI	'G'
	JZ	GO
	CPI	'D'
	JZ	DUMP
	CPI	'A'
	JZ	ASDUMP
	CPI	'Q'
	JZ	MAINLOOP
	CPI	'X'
	JZ	EXAMREGS
	.IFG	REGSS,[
	CPI	'R'
	JZ	REGISTER
]
	.IFG	MEMSS,[
	CPI	'M'
	JZ	MEMORY
	CPI	'P'
	JZ	PORT
]
	CPI	'S'
	JZ	STEP
	JMP	..DB1
	.PAGE
; ******************
; **
; **  BREAKPOINT
; **
; ******************
BREAK:	MVI	A,17		; 'BREAK ON '
	CALL	PRINTM
..BRK1:	CALL	INCHAR
	CPI	'M'
	LXI	B,200H+18
	JRZ	..BRK2
	CPI	'P'
	LXI	B,100H+19
	JRNZ	..BRK1
..BRK2:	MOV	A,C
	CALL	PRINTM
..BRK0:	CALL	INCHAR
	CPI	'R'
	JRNZ	..BK2
	SET	3,B
	MVI	A,20		; READ
	JMPR	..BK3
..BK2:	CPI	'W'
	JRNZ	..BRK0
	SET	2,B
	MVI	A,21
..BK3:	CALL	PRINTM
	MOV	A,B
	OUT	BTYPE
	STA	BTSAVE
	MVI	A,22		; ' AT '
	CALL	PRINTM
	CALL	KEYBD
	CALL	CONVRT
	MOV	A,C
	OUT	BADRL
	MOV	A,B
	OUT	BADRH
	JMP	DEBUG
	.PAGE
	.IFG	R2708,[.LOC	ICEROM+800H]
; **********
; **
; **  GO
; **
; **********
GO:	MVI	A,23
	CALL	PRINTM
	CALL	INCHAR
	CPI	0DH		; CR
	JRZ	..G2
	MVI	A,22		; AT
	CALL	PRINTM
	CALL	KEYBD
	CALL	CONVRT		; GET ADDRESS TO ..G TO
	MOV	H,B
	MOV	L,C
	SHLD	PCSAVE		;SAVE IN REGISTER AREA
..G2:	LDA	BTSAVE
	OUT	BTYPE
GO25:	XRA	A
	OUT	SELECT		; DISABLE FLOPPY INTERUPTS
	LXI	H,0C3F3H	; JP AND DI INSTRUCTIONS
	LDA	IFF	; INTERUPTS?
	ORA	A
	JRZ	..G3
	SET	3,L
..G3:	SHLD	EIDI	; LOADS JUMPER TOO
	SSPD	MONSP
	LXI	SP,PCSAVE+4
	POP	H
	POP	D
	POP	B
	EXX
	POP	PSW
	EXAF
	POP	Y
	POP	X
	POP	H
	POP	D
	POP	B
	POP	PSW
	LSPD	SPSAVE		; DON'T CHANGE FLAGS
	MVI	A,3		; TURN ON WRITE PROTECT
	OUT	MISC		; 4 M1'S TO ..G
	LDA	AFSAVE+1
	JMP	EIDI
	.PAGE
; ************
; **
; **  STEP
; **
; ************
STEP:	LXI	H,EXAMREGS
	SHLD	NMIJP
	LHLD	PCSAVE
	LXI	B,BADRH+0A00H
	OUTP	H
	INR	C
	OUTP	L
	INR	C
	OUTP	B	; SET BREAK TYPE
	JMP	GO25
	.PAGE
; **************
; **  MEMORY    **
; **	&	**
; **   PORT     **
; **************
	.IFG	MEMSS,[
MEMORY:	MVI	A,7		;"MEMORY "
	JMPR	P0
PORT:	LDA	DMPSTA	;GET STATUS BYTE
	SET	1,A		;SET PORT COMMAND BIT
	STA	DMPSTA
	MVI	A,29		;"PORT"
P0:	CALL	PRINTM
	CALL	KEYBD	;READ ADDRESS
	CALL	CONVRT	;MAKE IT BINARY
..P1:	LXI	H,KEYBUF
	MOV	D,B
	MOV	E,C
	CALL	DADDR	;PRINT ADDRESS ON TERMINAL
	LDA	DMPSTA
	BIT	1,A		;ARE WE IN PORT COMMAND????
	JRNZ	..M1
	MVI	A,5		; READ A EXT BYTE
	OUT	MISC
	LDAX	B	;READ FROM ..PORY LOCATION
	JMPR	..M2
..M1:	INP	A	;READ FROM USER TYPED PORT #
..M2:	CALL	ASCII
	LDA	DMPSTA	;CHECK IF ASCII BIT IS ON
	BIT	0,A		;PRINT BYTE IN ASCII??
	JRZ	..P1A
	BIT	1,A		;IF IN PORT COMMAND, NO ASCII
	JRNZ	..P1A
	MVI	M,SPACE
	INX	H
	MVI	M,SLASH
	INX	H
	MVI	A,5
	OUT	MISC	; TURN ON THE EXT SHIT
	LDAX	B	;GET DATA FROM MEMORY
	CALL	APRNT	;CHECK IF IT'S PRINTABLE
	MOV	M,A
	INX	H
	MVI	M,SLASH
	INX	H
..P1A:	MVI	M,SPACE+080H
	PUSH	B		;SAVE MEM LOCATION
	LXI	H,KEYBUF
	CALL	CONOMSG	;PRINT MEM & CONTENTS
	CALL	KEYBD	;READ ANY CHANGES
	LDAX	D
..P2:	CPI	COMMA
	JRZ	..P4
..P3:	CPI	CR		;DONE????
	JRNZ	..P5
..P4:	POP	B
	LDA	DMPSTA
	ANI	0FDH		;CLEAR OUT PORT BIT
	STA	DMPSTA
	JMP	DEBUG
..P5:	CPI	LF		;ADVANCE A LOCATION???
	JRNZ	..P6
	POP	B
	INX	B		;POINT AT NEXT LOC.
	JMPR	..P1
..P6:	CPI	ARROW	;GO BACKWARDS????
	JRNZ	..P7
	POP	B
	DCX	B		;DECREMENT PONITER
	JMPR	..P1
..P7:	CALL	CONVRT
	LDA	DMPSTA
	BIT	1,A		;IN PORT CO.MAND?????
	JRNZ	..M8
	MOV	A,C		;BINARY OF LAST TWO DIGITS TYPED
	POP	B		; GET BACK MEM LOCATION
	EXAF
