;***
;***  DUMP ROUTINE -
;***
;***  REGS  -  DE -> POINTS AT ..PORY
;***	HL -> OUTPUT BUFFER FOR 2-DIGIT HEX EQUIVALENTS
;***	BC ->   "	"	"  ASCII EQUIVALENT
